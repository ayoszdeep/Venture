import { useState } from "react";

export default function StudyPlanPanel() {
  const [credentials, setCredentials] = useState({
    email: "aarav@example.com",
    password: "Candidate123!",
  });
  const [plan, setPlan] = useState(null);
  const [planMeta, setPlanMeta] = useState(null);
  const [status, setStatus] = useState("idle");
  const [error, setError] = useState("");

  const updateField = (key) => (event) => {
    setCredentials((previous) => ({ ...previous, [key]: event.target.value }));
  };

  const generatePlan = async (event) => {
    event.preventDefault();
    setStatus("loading");
    setError("");

    try {
      const loginResponse = await fetch("/api/v1/auth/login", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify(credentials),
      });
      const loginJson = await loginResponse.json();

      if (!loginResponse.ok) {
        throw new Error(loginJson.message || "Login failed.");
      }

      const { token, user } = loginJson.data;

      const planResponse = await fetch(`/api/v1/ai/study-plan/${user.id}`, {
        headers: { Authorization: `Bearer ${token}` },
      });
      const planJson = await planResponse.json();

      if (!planResponse.ok) {
        throw new Error(planJson.message || "Study plan request failed.");
      }

      setPlan(planJson.data.studyPlan);
      setPlanMeta(planJson.meta);
      setStatus("ready");
    } catch (requestError) {
      setError(requestError.message || "Something went wrong.");
      setStatus("error");
    }
  };

  return (
    <div className="planner">
      <form className="planner-form" onSubmit={generatePlan}>
        <label>
          <span>Email</span>
          <input
            type="email"
            value={credentials.email}
            onChange={updateField("email")}
            required
          />
        </label>
        <label>
          <span>Password</span>
          <input
            type="password"
            value={credentials.password}
            onChange={updateField("password")}
            required
          />
        </label>
        <button type="submit" disabled={status === "loading"}>
          {status === "loading" ? "Generating…" : "Generate study plan"}
        </button>
      </form>

      {status === "error" && <p className="explorer-note">{error}</p>}

      {status === "ready" && plan && (
        <div className="planner-output">
          <p className="planner-meta">
            Generated by <strong>{planMeta?.generator}</strong> · grounded on{" "}
            {planMeta?.shortlistSize} aggregation-ranked programs · cache:{" "}
            {planMeta?.cache}
          </p>

          <p className="planner-summary">{plan.summary}</p>

          <div className="planner-columns">
            <section>
              <h3>Shortlist strategy</h3>
              <ul>
                {(plan.shortlistStrategy || []).map((item) => (
                  <li key={`${item.universityName}-${item.programTitle}`}>
                    <strong>{item.programTitle}</strong> —{" "}
                    {item.universityName}{" "}
                    <span className="pill">{item.category}</span>
                    <br />
                    <small>{item.rationale}</small>
                  </li>
                ))}
              </ul>
            </section>

            <section>
              <h3>Timeline</h3>
              <ul>
                {(plan.timeline || []).map((phase) => (
                  <li key={phase.phase}>
                    <strong>{phase.phase}</strong> — {phase.focus}
                    <ul>
                      {(phase.actions || []).map((action) => (
                        <li key={action}>
                          <small>{action}</small>
                        </li>
                      ))}
                    </ul>
                  </li>
                ))}
              </ul>
            </section>

            <section>
              <h3>Budget &amp; risks</h3>
              <ul>
                {(plan.budgetAdvice || []).map((note) => (
                  <li key={note}>
                    <small>{note}</small>
                  </li>
                ))}
                {(plan.risks || []).map((risk) => (
                  <li key={risk}>
                    <small>⚠ {risk}</small>
                  </li>
                ))}
              </ul>
            </section>
          </div>
        </div>
      )}
    </div>
  );
}
